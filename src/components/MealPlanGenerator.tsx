import { useState } from "react";
import { generateMealPlan } from "../lib/mealPlan";
import {
  exportOutcomeMessage,
  exportResultAsImage,
  type ExportOutcome,
} from "../lib/exportImage";
import { feetInchesToCm, lbToKg } from "../lib/units";
import type { ActivityLevel, Goal, MealPlanOutput, Sex } from "../lib/types";

const ACTIVITY_OPTIONS: { value: ActivityLevel; label: string }[] = [
  { value: "sedentary", label: "Sedentary (little to no exercise)" },
  { value: "light", label: "Light (1-3 days/week)" },
  { value: "moderate", label: "Moderate (3-5 days/week)" },
  { value: "very_active", label: "Very active (6-7 days/week)" },
];

const GOAL_OPTIONS: { value: Goal; label: string }[] = [
  { value: "fat_loss", label: "Fat loss" },
  { value: "maintenance", label: "Maintenance" },
  { value: "muscle_gain", label: "Muscle gain" },
];

const HEALTH_FLAG_QUESTIONS = [
  "Has a doctor ever told you that you have a heart condition?",
  "Do you have chest pain during physical activity?",
  "Are you currently pregnant or nursing?",
  "Do you have a diagnosed eating disorder, current or in recovery?",
  "Are you on medication that affects metabolism, heart rate, or blood sugar?",
];

export function MealPlanGenerator() {
  const [sex, setSex] = useState<Sex>("male");
  const [ageYears, setAgeYears] = useState(30);
  // Imperial in the UI, metric at the engine boundary — see lib/units.ts.
  const [heightFt, setHeightFt] = useState(5);
  const [heightIn, setHeightIn] = useState(10);
  const [weightLb, setWeightLb] = useState(176);
  const [activityLevel, setActivityLevel] = useState<ActivityLevel>("moderate");
  const [goal, setGoal] = useState<Goal>("maintenance");
  const [healthAnswers, setHealthAnswers] = useState<boolean[]>(
    HEALTH_FLAG_QUESTIONS.map(() => false),
  );
  const [result, setResult] = useState<MealPlanOutput | null>(null);
  const [justGenerated, setJustGenerated] = useState(false);
  const [saving, setSaving] = useState(false);
  const [saveOutcome, setSaveOutcome] = useState<ExportOutcome | null>(null);

  const healthFlags = healthAnswers.some(Boolean);

  function toggleHealthAnswer(index: number) {
    setHealthAnswers((prev) =>
      prev.map((v, i) => (i === index ? !v : v)),
    );
  }

  function handleGenerate() {
    setResult(
      generateMealPlan({
        sex,
        ageYears,
        heightCm: feetInchesToCm(heightFt, heightIn),
        weightKg: lbToKg(weightLb),
        activityLevel,
        goal,
        healthFlags,
      }),
    );
    setJustGenerated(true);
    setTimeout(() => setJustGenerated(false), 650);
  }

  async function handleSaveImage() {
    if (!result || result.blocked) return;
    setSaving(true);
    setSaveOutcome(null);
    const lines = [
      `Calories: ${result.macros.calories} kcal/day`,
      `Protein: ${result.macros.proteinG} g`,
      `Fat: ${result.macros.fatG} g`,
      `Carbs: ${result.macros.carbsG} g`,
      "",
      "7 days at these targets. Meal structure repeats daily — swap food",
      "sources freely as long as the day's totals hold.",
    ];
    const outcome = await exportResultAsImage(
      { title: "Meal Plan — 1 Week", subtitle: `${result.macros.calories} kcal/day`, lines },
      "meal-plan.png",
    );
    setSaving(false);
    setSaveOutcome(outcome);
  }

  return (
    <section className="tool">
      <h2>Meal Plan Generator</h2>
      <p className="tool-copy">
        One week of calorie and macro targets, calculated with Mifflin-St
        Jeor. Not generated by a model — the math is fixed and repeatable.
      </p>

      <div className="field">
        <label>Sex</label>
        <select value={sex} onChange={(e) => setSex(e.target.value as Sex)}>
          <option value="male">Male</option>
          <option value="female">Female</option>
        </select>
      </div>

      <div className="field-row">
        <div className="field">
          <label>Age</label>
          <input
            type="number"
            value={ageYears}
            min={13}
            max={90}
            onChange={(e) => setAgeYears(Number(e.target.value))}
          />
        </div>
        <div className="field">
          <label>Height (ft)</label>
          <input
            type="number"
            inputMode="numeric"
            value={heightFt}
            min={4}
            max={7}
            onChange={(e) => setHeightFt(Number(e.target.value))}
          />
        </div>
        <div className="field">
          <label>Height (in)</label>
          <input
            type="number"
            inputMode="numeric"
            value={heightIn}
            min={0}
            max={11}
            onChange={(e) => setHeightIn(Number(e.target.value))}
          />
        </div>
        <div className="field">
          <label>Weight (lbs)</label>
          <input
            type="number"
            inputMode="numeric"
            value={weightLb}
            min={80}
            max={550}
            onChange={(e) => setWeightLb(Number(e.target.value))}
          />
        </div>
      </div>

      <div className="field">
        <label>Activity level</label>
        <select
          value={activityLevel}
          onChange={(e) => setActivityLevel(e.target.value as ActivityLevel)}
        >
          {ACTIVITY_OPTIONS.map((opt) => (
            <option key={opt.value} value={opt.value}>
              {opt.label}
            </option>
          ))}
        </select>
      </div>

      <div className="field">
        <label>Goal</label>
        <div className="pill-row">
          {GOAL_OPTIONS.map((opt) => (
            <button
              key={opt.value}
              type="button"
              className={goal === opt.value ? "pill pill-active" : "pill"}
              onClick={() => setGoal(opt.value)}
            >
              {opt.label}
            </button>
          ))}
        </div>
      </div>

      <div className="field">
        <label>Before we generate anything, answer honestly:</label>
        {HEALTH_FLAG_QUESTIONS.map((q, i) => (
          <label key={q} className="checkbox-row">
            <input
              type="checkbox"
              checked={healthAnswers[i]}
              onChange={() => toggleHealthAnswer(i)}
            />
            {q}
          </label>
        ))}
      </div>

      <button
        type="button"
        className={justGenerated ? "primary btn-confirm" : "primary"}
        onClick={handleGenerate}
      >
        Generate week
      </button>

      {result && result.blocked && (
        <div className="result result-blocked">
          <p>{result.reason}</p>
        </div>
      )}

      {result && !result.blocked && (
        <div className="result">
          <span className="confirm-badge" aria-hidden="true">
            ✓
          </span>
          <div className="bento-grid">
            <div className="bento-tile bento-tile-hero">
              <span className="bento-label">Calories / day</span>
              <span className="bento-value">{result.macros.calories}</span>
              <span className="bento-unit">kcal</span>
            </div>
            <div className="bento-tile">
              <span className="bento-label">Protein</span>
              <span className="bento-value">
                {result.macros.proteinG}
                <span className="bento-unit-inline">g</span>
              </span>
            </div>
            <div className="bento-tile">
              <span className="bento-label">Fat</span>
              <span className="bento-value">
                {result.macros.fatG}
                <span className="bento-unit-inline">g</span>
              </span>
            </div>
            <div className="bento-tile">
              <span className="bento-label">Carbs</span>
              <span className="bento-value">
                {result.macros.carbsG}
                <span className="bento-unit-inline">g</span>
              </span>
            </div>
          </div>
          <p className="result-note">
            Same targets, 7 days. Meal structure repeats daily — swap food
            sources as needed as long as the day's totals hold.
          </p>
          <p className="disclaimer">{result.disclaimer}</p>
          <button
            type="button"
            className="secondary"
            onClick={handleSaveImage}
            disabled={saving}
          >
            {saving ? "Saving…" : "Save to Photos / Files"}
          </button>
          {saveOutcome && (
            <p
              className={
                saveOutcome === "failed" ? "field-error" : "result-note"
              }
              role="status"
            >
              {exportOutcomeMessage(saveOutcome)}
            </p>
          )}
        </div>
      )}

      {/* Always visible, result or not: this calculator sets calorie
          targets without a full health screen. */}
      <p className="disclaimer health-note">
        General education, not medical advice. If you are pregnant, have a medical condition, take medication, or have a history of an eating disorder, talk to a doctor or registered dietitian before changing how you eat.
      </p>
    </section>
  );
}
